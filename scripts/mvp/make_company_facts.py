"""Write workspace/config/company.facts.json: the company facts of the intake chat, as of the fork date T.

The intake chat of the cases page (workspace/src/variator/case/intake) may say only facts from this file,
the user's words and the case configs. The source is ``variator.orgsim.company.spec.default_spec`` (people,
departments, the CEO, key clients, the client cohort and vendors) plus the staff changes of the final history
before T (``LEFT`` and ``BACKFILLS``: the people who left and the backfills in their seats) and the ARR of each
key client at T (``ARR_AT_T``; ``acv`` is the value at the start of the history). So the people are the staff
at T. ARR, cash and the fork date come from the case configs. tests/mvp/test_company_facts.py checks
the file against the spec and, where it is present, the roster at T of the actor engine (``ACTORS``).

Run with VARIATOR's venv:
    .venv/bin/python scripts/mvp/make_company_facts.py
"""

# ruff: noqa: E501 - one staff change per line

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from variator.orgsim.company.spec import CompanySpec, default_spec

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "workspace/config/company.facts.json"
#: The roster at T of the actor engine (WP10); the test compares the staff with it when the file exists.
ACTORS = Path("/tmp/variator-1000/mvp-artifacts/actors/actors.json")
SCHEMA = "variator-company-facts/1"
AS_OF = "2026-10-26"
SOURCE = (
    "Generated by scripts/mvp/make_company_facts.py from the company history spec "
    "(src/variator/orgsim/company/spec.py, default_spec) and the staff changes of the final history "
    "before the fork date: people on staff at T, departments, key clients, the client cohort and vendors. "
    "ARR, cash and the fork date come from the case configs. Do not edit by hand."
)
# The final history before T (actors.json, status_at_t): who left, and who joined in the seat.
LEFT = {"LW-E11": "2025-12-29", "LW-E12": "2026-01-27", "LW-E17": "2026-04-27"}
# ARR of each key client at T (actors.json arr_at_t; the spec has the ACV at the start of the history)
ARR_AT_T = {
    "CL-001": 1_022_400, "CL-002": 932_400, "CL-003": 630_000, "CL-004": 552_000, "CL-005": 789_600, "CL-006": 433_200,
}  # fmt: skip
# The state at T of the metric catalogue (history-metrics-ceo/metrics/<id>.json, result.value; percent as a share):
# the case B layer calibrates the formula inputs to it (scripts/mvp/case_calibration.py)
METRICS_AT_T = {
    "rev.arr": 12_001_200, "fin.cash": 2_000_000, "rev.churn": 0.1234, "ops.sla": 0.99991, "ops.latency": 181.8,
    "cust.nps": 30.1, "ops.incidents": 1.0, "ops.mttr": 1.81, "ops.deploys": 9.75, "ops.team_load": 0.945,
    "fin.dso": 62.0,
}  # fmt: skip
CATALOGUE = Path("/tmp/variator-1000/mvp-artifacts/history-metrics-ceo/metrics")
PAYROLL_AT_T = 2_397_900  # gross salaries of the staff at T a year (actors.json salary_at_t)
# id, name, title, seat (the person who left), manager, start
BACKFILLS = [
    ("LW-E21", "Edward Costa", "Frontend Engineer", "LW-E11", "LW-E06", "2026-03-09"),
    ("LW-E22", "Victor Osei", "DevOps Engineer", "LW-E12", "LW-E03", "2026-04-13"),
    ("LW-E23", "Tariq Nash", "Support Engineer", "LW-E17", "LW-E16", "2026-06-01"),
]


def _mid_sentence(name: str) -> str:
    """A department name inside a sentence: "Finance and HR" -> "finance and HR" (acronyms stay)."""
    return name[:1].lower() + name[1:]


def _number(x: float) -> int | float:
    return int(x) if float(x).is_integer() else x


def staff_at_t(spec: CompanySpec) -> list[dict[str, Any]]:
    """People on staff at T: the spec people who did not leave, then the backfills (in their seats' department).

    A manager who left is replaced by the person in that seat at T."""
    dept_id = {d.name: d.id for d in spec.departments}
    seat = {s: pid for pid, _n, _t, s, _m, _d in BACKFILLS}
    by_id = {p.id: p for p in spec.people}
    people = [
        {
            "id": p.id,
            "name": p.name,
            "title": p.title,
            "department": dept_id.get(p.department, p.department),
            "manager": seat.get(p.manager, p.manager),
        }
        for p in spec.people
        if p.id not in LEFT
    ]
    for pid, name, title, was, manager, _start in BACKFILLS:
        dept = by_id[was].department
        people.append(
            {"id": pid, "name": name, "title": title, "department": dept_id.get(dept, dept), "manager": manager}
        )
    return people


def build_facts(spec: CompanySpec | None = None) -> dict[str, Any]:
    spec = spec or default_spec()
    ceo = next((p for p in spec.people if p.role_id == "ceo"), None) or next(
        p for p in spec.people if p.manager is None
    )
    seat = {s: pid for pid, _n, _t, s, _m, _d in BACKFILLS}
    return {
        "schema": SCHEMA,
        "source": SOURCE,
        "asOf": AS_OF,
        "company": spec.company.name,
        "people": staff_at_t(spec),
        "departments": [
            {"id": d.id, "name": _mid_sentence(d.name), "head": seat.get(d.head, d.head)}
            for d in spec.departments
        ],
        "ceo": ceo.id,
        "keyClients": [
            {
                "id": c.id,
                "name": c.name,
                "acv": _number(c.acv),
                "arrAtT": ARR_AT_T[c.id],
                "renewalInMonths": c.renewal_in_months,
            }
            for c in spec.key_clients
        ],
        "otherClients": spec.cohort.count,
        "vendors": [{"id": v.id, "name": v.name, "kind": v.kind} for v in spec.vendors],
        "payrollAtT": PAYROLL_AT_T,
        "metricsAtT": dict(METRICS_AT_T),
    }


def write(path: Path = OUT) -> Path:
    path.write_text(json.dumps(build_facts(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write())
